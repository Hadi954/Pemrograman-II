    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {                                         
        try {
            String noMeja = jTextField1.getText();
            double totalPesanan = Double.parseDouble(jTextField2.getText());
            double ppn = totalPesanan * 0.11;
            double totalBayar = totalPesanan + ppn;
            double uangPembayaran = Double.parseDouble(jTextField4.getText());
            
            if (uangPembayaran < totalBayar) {
                javax.swing.JOptionPane.showMessageDialog(this, "Uang pembayaran kurang!");
                return;
            }
            
            double uangKembali = uangPembayaran - totalBayar;
            
            jTextField3.setText(String.valueOf(ppn));
            jTextField5.setText(String.valueOf(uangKembali));
            
            // Add to table
            tableModel.addRow(new Object[]{noMeja, totalPesanan, ppn, totalBayar});
            
            // Update Total Pendapatan
            totalPendapatan += totalBayar;
            jTextField6.setText(String.valueOf(totalPendapatan));
            
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Masukkan angka yang valid!");
        }
    }                                        

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {                                         
        try {
            String noMeja = jTextField1.getText();
            String totalPesanan = jTextField2.getText();
            String ppn = jTextField3.getText();
            
            if (totalPesanan.isEmpty() || ppn.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Klik BAYAR terlebih dahulu!");
                return;
            }
            
            double dTotalPesanan = Double.parseDouble(totalPesanan);
            double dPpn = Double.parseDouble(ppn);
            double dTotalBayar = dTotalPesanan + dPpn;
            
            String uangBayar = jTextField4.getText();
            String uangKembali = jTextField5.getText();
            
            String struk = "========== STRUK PEMBAYARAN ==========\n"
                         + "No Meja        : " + noMeja + "\n"
                         + "Total Pesanan  : Rp " + String.format("%.2f", dTotalPesanan) + "\n"
                         + "PPN (11%)      : Rp " + String.format("%.2f", dPpn) + "\n"
                         + "--------------------------------------\n"
                         + "Total Bayar    : Rp " + String.format("%.2f", dTotalBayar) + "\n"
                         + "Uang Bayar     : Rp " + uangBayar + "\n"
                         + "Uang Kembali   : Rp " + uangKembali + "\n"
                         + "======================================\n"
                         + "          Terima Kasih!          ";
            txtStruk.setText(struk);
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Data tidak valid!");
        }
    }                                        

