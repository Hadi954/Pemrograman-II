    private void calculateLive() {
        try {
            double totalPesanan = jTextField2.getText().isEmpty() ? 0 : Double.parseDouble(jTextField2.getText());
            double ppn = totalPesanan * 0.11;
            jTextField3.setText(String.valueOf(ppn));

            if (!jTextField4.getText().isEmpty()) {
                double uangPembayaran = Double.parseDouble(jTextField4.getText());
                double totalBayar = totalPesanan + ppn;
                double uangKembali = uangPembayaran - totalBayar;
                jTextField5.setText(String.valueOf(uangKembali));
            } else {
                jTextField5.setText("");
            }
        } catch (NumberFormatException e) {
            // Ignore during typing
        }
    }

